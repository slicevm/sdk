// Regenerates packages/cli-<target>/ from packages/platforms.json and syncs the
// @slicevm/cli wrapper (optionalDependencies + embedded target table).
// Platform packages are generated artifacts: never edit them by hand.
//
// Usage: node scripts/npm/generate-platform-packages.mjs
import { existsSync } from "node:fs";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { loadManifest, packagesDir, readJson, writeJson } from "./lib.mjs";

